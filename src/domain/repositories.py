from typing import Protocol, Optional
from .model import Habitacion, Reservacion

class HabitacionRepository(Protocol):
    def obtener(self, habitacion_id: str) -> Optional[Habitacion]: ...
    def buscar_disponibles(self, entrada, salida, categoria: str) -> list[Habitacion]: ...
    def guardar(self, habitacion: Habitacion) -> None: ...

class ReservacionRepository(Protocol):
    def obtener(self, reservacion_id: str) -> Optional[Reservacion]: ...
    def guardar(self, reservacion: Reservacion) -> None: ...

class UnitOfWork(Protocol):
    def confirmar(self) -> None: ...
    def revertir(self) -> None: ...
